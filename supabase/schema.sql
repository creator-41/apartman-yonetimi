-- Additive schema: does not modify any acisu_* table, policy, user or trigger.
create schema if not exists apartman_private;
revoke all on schema apartman_private from public, anon, authenticated;
grant usage on schema apartman_private to anon, authenticated;

create table public.apartman_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
create table public.apartman_units (
  id integer generated by default as identity primary key,
  label text not null check (length(label) between 1 and 60),
  owner text not null default '' check (length(owner)<=100),
  resident text not null default '' check (length(resident)<=100),
  exempt boolean not null default false
);
create table public.apartman_charges (
  id integer generated always as identity primary key,
  unit_id integer not null references public.apartman_units(id),
  period text not null check (period ~ '^20[0-9]{2}-(0[1-9]|1[0-2])$'),
  amount bigint not null check (amount between 1 and 1000000000),
  created_at timestamptz not null default now(),
  unique(unit_id,period)
);
create table public.apartman_payments (
  id integer generated always as identity primary key,
  charge_id integer not null references public.apartman_charges(id),
  amount bigint not null check (amount between 1 and 1000000000),
  date date not null,
  note text not null default '' check (length(note)<=200),
  created_at timestamptz not null default now()
);
create index apartman_payments_charge_idx on public.apartman_payments(charge_id);
create table public.apartman_expenses (
  id integer generated always as identity primary key,
  category text not null check (category in ('Temizlik','Elektrik','Su','Asansör','Bakım / Onarım','Yönetim gideri','Diğer')),
  description text not null check (length(description) between 1 and 300),
  amount bigint not null check (amount between 1 and 1000000000),
  date date not null,
  created_at timestamptz not null default now()
);
create index apartman_expenses_date_idx on public.apartman_expenses(date);
create table public.apartman_notices (
  id integer generated always as identity primary key,
  title text not null check (length(title) between 1 and 100),
  body text not null check (length(body) between 1 and 2000),
  created_at timestamptz not null default now()
);
create table public.apartman_settings (
  id integer primary key default 1 check (id=1),
  name text not null check (length(name) between 1 and 100),
  monthly_dues bigint not null check (monthly_dues between 1 and 1000000000),
  opening_balance bigint not null check (opening_balance between 0 and 1000000000)
);
create table public.apartman_audit (
  id integer generated always as identity primary key,
  actor uuid not null default auth.uid(),
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

